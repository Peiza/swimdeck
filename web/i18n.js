export function makeT(lang) {
  const dict = T[lang] || T.sv;
  return (key, vars = {}) =>
    (dict[key] ?? T.sv[key] ?? key).replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}

export function detectLang() {
  try {
    // stored as JSON ("\"sv\"") by the app; older versions stored the bare code
    const raw = localStorage.getItem('swimdeck.lang');
    let saved = raw;
    try { saved = JSON.parse(raw); } catch {}
    if (saved && T[saved]) return saved;
  } catch {}
  // Norwegian browsers report no, nb or nn; all get the bokmål texts
  const nav = (navigator.languages || [navigator.language || 'sv']).map((l) => l.slice(0, 2)).map((l) => (l === 'no' || l === 'nn' ? 'nb' : l));
  return nav.find((l) => T[l]) || 'sv';
}
