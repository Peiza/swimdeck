#!/usr/bin/env node
// Builds web/wr-data.js from tools/wr-source.txt (current World Aquatics world records, individual events).
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync(new URL('./wr-source.txt', import.meta.url), 'utf8');
const MONTHS = { Jan: '01', Feb: '02', Mar: '03', Apr: '04', May: '05', Jun: '06', Jul: '07', Aug: '08', Sep: '09', Oct: '10', Nov: '11', Dec: '12' };
const fm = src.match(/fetched (\d{1,2}) (\w{3}) (\d{4})/);
const fetched = fm ? `${fm[3]}-${MONTHS[fm[2]]}-${fm[1].padStart(2, '0')}` : '';
const records = {};
for (const line of src.split('\n')) {
  if (!line.trim() || line.startsWith('#')) continue;
  const m = line.match(/^([LS][WM]\d+(?:fr|ba|br|fl|im)) (\d+)$/);
  if (!m) throw new Error('Bad line: ' + line);
  records[m[1]] = Number(m[2]);
}
writeFileSync(new URL('../web/wr-data.js', import.meta.url), `// Generated by tools/build-records.js from tools/wr-source.txt. Do not edit by hand.
// Current World Aquatics world records (individual events), times in hundredths.
export const WR = ${JSON.stringify({ fetched, records })};
`);
console.log(`web/wr-data.js: ${Object.keys(records).length} records, fetched ${fetched}`);
