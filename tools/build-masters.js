#!/usr/bin/env node
// Builds web/masters-data.js from tools/masters-source-<year>.txt (World Aquatics Masters World Records).
// Run: node tools/build-masters.js 2026
import { readFileSync, writeFileSync } from 'node:fs';

const year = Number(process.argv[2] || 2026);
const src = readFileSync(new URL(`./masters-source-${year}.txt`, import.meta.url), 'utf8');
const AGES = Array.from({ length: 17 }, (_, i) => 25 + i * 5);
const asOf = (src.match(/as of (\d{2} \w{3} \d{4})/) || [])[1] || '';
const records = {};
let n = 0;
for (const line of src.split('\n')) {
  if (!line.trim() || line.startsWith('#')) continue;
  const m = line.match(/^([LS])([WM])(\d+)(fr|ba|br|fl|im) ([\d,]*)$/);
  if (!m) throw new Error('Bad line: ' + line);
  const times = m[5].split(',').map((x) => (x ? Number(x) : null));
  if (times.length !== AGES.length) throw new Error(`Expected ${AGES.length} age groups: ${line}`);
  records[`${m[1]}${m[2]}${m[3]}${m[4]}`] = times;
  n += times.filter(Boolean).length;
}
writeFileSync(new URL('../web/masters-data.js', import.meta.url), `// Generated by tools/build-masters.js from tools/masters-source-${year}.txt. Do not edit by hand.
// World Aquatics Masters World Records (individual), times in hundredths per five-year age group from 25-29.
export const MASTERS = ${JSON.stringify({ asOf, ages: AGES, records })};
`);
console.log(`web/masters-data.js: ${Object.keys(records).length} events, ${n} records, as of ${asOf}`);
