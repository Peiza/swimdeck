#!/usr/bin/env node
// Builds web/wps-data.js from tools/wps-source-<year>.txt (World Para Swimming point score parameters).
// Run: node tools/build-wps.js 2024
import { readFileSync, writeFileSync } from 'node:fs';

const year = Number(process.argv[2] || 2024);
const src = readFileSync(new URL(`./wps-source-${year}.txt`, import.meta.url), 'utf8');
const data = src.split('\n').filter((l) => l.trim() && !l.startsWith('#')).join(';');

const events = {};
let ev = null;
for (const part of data.split(';').map((s) => s.trim()).filter(Boolean)) {
  const t = part.split(/\s+/);
  if (t[0] === 'E') {
    ev = { key: t[1], bM: Number(t[2]), bW: Number(t[3]) };
    events[ev.key] = {};
    continue;
  }
  if (!ev || !/^(S|SB|SM)\d{1,2}$/.test(t[0])) throw new Error('Bad row: ' + part);
  let bM = ev.bM;
  let bW = ev.bW;
  for (const x of t.slice(3)) {
    if (x[0] === 'm') bM = Number(x.slice(1));
    else if (x[0] === 'w') bW = Number(x.slice(1));
    else throw new Error('Bad override: ' + part);
  }
  // [b men, c men, b women, c women]
  events[ev.key][t[0]] = [bM, Number(t[1]), bW, Number(t[2])];
}
const rows = Object.values(events).reduce((n, e) => n + Object.keys(e).length, 0);
const out = `// Generated by tools/build-wps.js from tools/wps-source-${year}.txt. Do not edit by hand.
// World Para Swimming Point Scores ${year}, long course. q = a * exp(-exp(b - c / p)), a = 1200, p in seconds.
export const WPS = ${JSON.stringify({ year, a: 1200, events })};
`;
writeFileSync(new URL('../web/wps-data.js', import.meta.url), out);
console.log(`web/wps-data.js: ${Object.keys(events).length} events, ${rows} rows`);
