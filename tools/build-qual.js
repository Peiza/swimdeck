#!/usr/bin/env node
// Builds web/qual-data.js from tools/qual-source-<year>.txt.
// Run: node tools/build-qual.js 2026
import { readFileSync, writeFileSync } from 'node:fs';

const year = Number(process.argv[2] || 2026);
const src = readFileSync(new URL(`./qual-source-${year}.txt`, import.meta.url), 'utf8');

const BASE = {
  frisim: { 50: 11, 100: 13, 200: 15, 400: 17, 800: 19, 1500: 21 },
  bröstsim: { 50: 31, 100: 33, 200: 35 },
  ryggsim: { 50: 41, 100: 43, 200: 45 },
  fjärilsim: { 50: 51, 100: 53, 200: 55 },
  medley: { 100: 61, 200: 63, 400: 65 },
};
function code(name, pool) {
  const m = name.toLowerCase().match(/^(\d+)m\s+(frisim|bröstsim|ryggsim|fjärilsim|medley)$/);
  if (!m) throw new Error('Unknown event: ' + name);
  const c = BASE[m[2]][Number(m[1])];
  if (!c) throw new Error('Unknown distance: ' + name);
  return pool === 50 ? c + 1 : c;
}
const num = (s) => (s === '' ? null : Number(s));

const usm = [];
const smA = [];
const smB = [];
const paraA = [];
const paraB = [];
const AGES = [[13, 14], [15, 16], [17, 18]];

for (const line of src.split('\n')) {
  if (!line.trim() || line.startsWith('#')) continue;
  const f = line.split('|');
  if (f[0] === 'usm') {
    const [, sex, ev, vals] = f;
    vals.split(',').map(num).forEach((t, i) => {
      if (t) usm.push([sex, AGES[Math.floor(i / 2)][0], code(ev, i % 2 ? 50 : 25), t]);
    });
  } else if (f[0] === 'sm') {
    const [, ev, vals] = f;
    const cols = [['A', 'W', 25], ['A', 'W', 50], ['A', 'M', 25], ['A', 'M', 50], ['B', 'W', 25], ['B', 'W', 50], ['B', 'M', 25], ['B', 'M', 50]];
    vals.split(',').map(num).forEach((t, i) => {
      if (!t) return;
      const [tier, sex, pool] = cols[i];
      (tier === 'A' ? smA : smB).push([sex, code(ev, pool), t]);
    });
  } else if (f[0] === 'para') {
    const [, sex, tier, ev, prefix, vals] = f;
    vals.split(',').map(num).forEach((t, i) => {
      if (!t) return;
      // Para times count the same in 25 m and 50 m pools.
      for (const pool of [25, 50]) (tier === 'A' ? paraA : paraB).push([sex, `${prefix}${i + 1}`, code(ev, pool), t]);
    });
  }
}

const PAGE = 'https://svensksimidrott.se/vara-simidrotter/simning/tavling/kvaltider';
const data = {
  year,
  checked: '2026-10-22',
  page: PAGE,
  // Qualifying period: 1 January of the year before the competition year until the day before the last regular entry date.
  windowStart: `${year - 1}-01-01`,
  standards: [
    { id: 'smA', comp: 'sm', tier: 'A', doc: 'https://svensksimidrott.se/download/18.1f53a16619be68dd13bb9af7/1780581490235/Kvaltider_SM_U21-SM_2026.pdf', version: '2026-06-04', rows: smA },
    { id: 'smB', comp: 'sm', tier: 'B', doc: 'https://svensksimidrott.se/download/18.1f53a16619be68dd13bb9af7/1780581490235/Kvaltider_SM_U21-SM_2026.pdf', version: '2026-06-04', rows: smB },
    { id: 'usm', comp: 'usm', tier: '', ages: AGES, doc: 'https://svensksimidrott.se/download/18.350f6944199c8ea1c0b88ecd/1760340300317/Kvaltider%20USM%20%2850m%29%202026.pdf', version: '2025-10-13', rows: usm },
    { id: 'paraA', comp: 'para', tier: 'A', doc: 'https://svensksimidrott.se/download/18.6ffd3b3119d24beaa6e1f19b/1774512522601/Kvaltider%20para%20SM%202026%20A%20och%20B%20kval%20v3.pdf', version: 'v3', rows: paraA },
    { id: 'paraB', comp: 'para', tier: 'B', doc: 'https://svensksimidrott.se/download/18.6ffd3b3119d24beaa6e1f19b/1774512522601/Kvaltider%20para%20SM%202026%20A%20och%20B%20kval%20v3.pdf', version: 'v3', rows: paraB },
  ],
};

const out = `// Generated by tools/build-qual.js from tools/qual-source-${year}.txt. Do not edit by hand.
// Row formats: SM [sex, event, time], USM [sex, ageFrom, event, time], Para [sex, class, event, time].
// Times in hundredths of a second, event codes as in Tempus Open (odd = 25 m pool, even = 50 m pool).
export const QUAL = ${JSON.stringify(data)};
`;
writeFileSync(new URL('../web/qual-data.js', import.meta.url), out);
console.log(`qual-data.js: SM A ${smA.length}, SM B ${smB.length}, USM ${usm.length}, Para A ${paraA.length}, Para B ${paraB.length}`);
